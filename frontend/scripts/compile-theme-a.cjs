// One deterministic cascade for the approved Midnight Felt design.
// Existing geometry is retained in a lower-priority layer. Theme colours,
// fonts and states win even over legacy, high-specificity !important rules.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const postcss = require('postcss');
const app = path.resolve(__dirname, '../src/app');
const baseNames = ['globals.css','pkr-app.css','pkr-casino.css','pre-game.css',
 'pkr-reference-polish.css','pkr-approved-banner.css','pkr-secondary-ui.css',
 'pkr-interaction-refresh.css','pkr-standings.css','pkr-landing-premium.css',
 'pkr-marketing-pages.css','pkr-product-gallery.css','pkr-2026-graphite.css'];
const themeNames = ['pkr-theme-a-tokens.css','pkr-theme-a-public.css',
 'pkr-theme-a-app.css','pkr-theme-a-table.css','pkr-theme-a-polish.css'];
function read(names) {
 const root = postcss.root();
 for (const name of names) {
  const css = fs.readFileSync(path.join(app,name),'utf8');
  const parsed = postcss.parse(css,{from:path.join(app,name)});
  root.append(parsed.nodes.map(node=>node.clone()));
 }
 root.walkComments(node=>node.remove());
 return root;
}
function selectDeclarations(root, important) {
 const selected = root.clone();
 selected.walkDecls(node=>{ if(Boolean(node.important)!==important)node.remove(); });
 function prune(node) {
  if(!node.nodes)return;
  for(const child of [...node.nodes]) {
   prune(child);
   if(child.nodes && child.nodes.length===0)child.remove();
  }
 }
 prune(selected);
 return selected;
}
const base = read(baseNames), theme = read(themeNames);
const out = postcss.root();
out.append(postcss.comment({text:'Generated by scripts/compile-theme-a.cjs. Edit the source theme files, not this output.'}));
// Important layer precedence is deliberately reversed by CSS. Keeping the
// theme's important declarations first and normal declarations last wins both.
out.append(postcss.atRule({name:'layer',params:'pkr-theme-priority, pkr-layout, pkr-theme'}));
const layout = postcss.atRule({name:'layer',params:'pkr-layout'});
layout.append(base.nodes);out.append(layout);
const priority = postcss.atRule({name:'layer',params:'pkr-theme-priority'});
priority.append(selectDeclarations(theme,true).nodes);out.append(priority);
const normal = postcss.atRule({name:'layer',params:'pkr-theme'});
normal.append(selectDeclarations(theme,false).nodes);out.append(normal);
const css = out.toString();
fs.writeFileSync(path.join(app,'pkr-theme-a.css'),css+'\n');
const manifest={theme:'Theme A - Midnight Felt',cssSha256:crypto.createHash('sha256').update(css).digest('hex'),
 colours:{background:'#0B0F12',surface:'#131A1F',raised:'#1B242B',line:'#26323A',text:'#EAF0F2',muted:'#8A99A3',primary:'#3DDC97',money:'#F2B84B',danger:'#FF5A5F',felt:'#0F5C4A'},
 fonts:['Bricolage Grotesque','Inter','JetBrains Mono']};
fs.writeFileSync(path.resolve(__dirname,'../public/design-version.json'),JSON.stringify(manifest,null,2)+'\n');
console.log('Compiled one Midnight Felt cascade: '+manifest.cssSha256.slice(0,12));
